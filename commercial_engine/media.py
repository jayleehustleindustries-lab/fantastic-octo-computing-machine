"""FFmpeg/ffprobe helpers. Every scene is normalised to the same codec params so
the final commercial is a lossless concat.

HUD text never touches the filtergraph: it is written to a file and passed via
``drawtext=textfile=``, so ``:`` ``,`` ``'`` ``%`` in copy can't break the
filter. File paths that do go into the graph are generated by us and checked
against a strict character set.
"""
from __future__ import annotations

import asyncio
import json
import re
from pathlib import Path

from .config import settings

SAFE_PATH_RE = re.compile(r"^[A-Za-z0-9/_.\-]+$")


class MediaError(RuntimeError):
    pass


async def run(*args: str) -> str:
    proc = await asyncio.create_subprocess_exec(*args, stdout=asyncio.subprocess.PIPE, stderr=asyncio.subprocess.PIPE)
    out, err = await proc.communicate()
    if proc.returncode != 0:
        tail = err.decode(errors="replace").strip().splitlines()[-8:]
        raise MediaError(f"{args[0]} exited {proc.returncode}: " + " | ".join(tail))
    return out.decode(errors="replace")


async def probe(path: Path) -> dict:
    out = await run("ffprobe", "-v", "error", "-show_entries", "format=duration:stream=codec_type", "-of", "json", str(path))
    return json.loads(out)


async def duration(path: Path) -> float:
    info = await probe(path)
    try:
        value = float(info["format"]["duration"])
    except (KeyError, TypeError, ValueError) as exc:
        raise MediaError(f"cannot read duration of {path}") from exc
    if value <= 0:
        raise MediaError(f"{path} has zero duration")
    return value


async def is_valid_video(path: Path) -> bool:
    """True only for a real, non-empty file with a video stream (never a stub)."""
    if not path.is_file() or path.stat().st_size == 0:
        return False
    try:
        info = await probe(path)
    except MediaError:
        return False
    return any(s.get("codec_type") == "video" for s in info.get("streams", []))


def graph_path(path: Path) -> str:
    resolved = str(path.resolve())
    if not SAFE_PATH_RE.match(resolved):
        raise MediaError(f"path {resolved!r} has characters unsafe for an ffmpeg filtergraph")
    return resolved


def hud_font_size(text: str) -> int:
    # Shrink long lines so they fit inside ~90% of the frame width.
    usable = settings.video_width * 0.9
    fitted = int(usable / (0.68 * max(len(text), 1)))
    return max(28, min(settings.hud_font_size, fitted))


def drawtext(textfile: Path, *, size: int, y: str, color: str | None = None, box: bool = True) -> str:
    parts = [
        f"fontfile={graph_path(Path(settings.hud_font_file))}",
        f"textfile={graph_path(textfile)}",
        f"fontsize={size}",
        f"fontcolor={color or settings.hud_text_color}",
        "x=(w-text_w)/2",
        f"y={y}",
    ]
    if box:
        parts += ["box=1", f"boxcolor={settings.hud_box_color}", "boxborderw=24"]
    return "drawtext=" + ":".join(parts)


def _encode_args(seconds: float) -> list[str]:
    return [
        "-t", f"{seconds:.3f}",
        "-c:v", "libx264", "-preset", "veryfast", "-crf", "20", "-pix_fmt", "yuv420p",
        "-r", str(settings.video_fps),
        "-c:a", "aac", "-b:a", "160k", "-ar", "48000", "-ac", "2",
        "-movflags", "+faststart",
    ]


def _frame_filter() -> str:
    w, h = settings.video_width, settings.video_height
    return f"scale={w}:{h}:force_original_aspect_ratio=increase,crop={w}:{h},fps={settings.video_fps},setsar=1,format=yuv420p"


async def compose_scene(*, visual: Path, narration: Path, hud_text: str, seconds: float, out: Path) -> Path:
    """Fit ``visual`` to ``seconds`` (loop/trim), burn the HUD, lay narration on top."""
    out.parent.mkdir(parents=True, exist_ok=True)
    textfile = out.with_suffix(".hud.txt")
    textfile.write_text(hud_text, encoding="utf-8")
    vf = f"[0:v]{_frame_filter()},{drawtext(textfile, size=hud_font_size(hud_text), y='h*0.12')}[v]"
    af = "[1:a]aresample=48000,apad[a]"
    tmp = out.with_suffix(".tmp.mp4")
    await run(
        "ffmpeg", "-y", "-v", "error",
        "-stream_loop", "-1", "-i", str(visual),
        "-i", str(narration),
        "-filter_complex", f"{vf};{af}",
        "-map", "[v]", "-map", "[a]",
        *_encode_args(seconds),
        str(tmp),
    )
    tmp.replace(out)  # atomic: a half-written file is never mistaken for done
    return out


async def end_card(out: Path) -> Path:
    out.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        (settings.brand_name, 120, "h*0.38", "white"),
        (settings.cta_text, 64, "h*0.50", "white"),
        (settings.cta_url, 72, "h*0.58", "0x00B4FF"),
    ]
    filters = []
    for i, (text, size, y, color) in enumerate(lines):
        tf = out.with_suffix(f".line{i}.txt")
        tf.write_text(text, encoding="utf-8")
        filters.append(drawtext(tf, size=size, y=y, color=color, box=False))
    w, h, fps = settings.video_width, settings.video_height, settings.video_fps
    tmp = out.with_suffix(".tmp.mp4")
    await run(
        "ffmpeg", "-y", "-v", "error",
        "-f", "lavfi", "-i", f"color=c={settings.end_card_background}:s={w}x{h}:r={fps}",
        "-f", "lavfi", "-i", "anullsrc=r=48000:cl=stereo",
        "-vf", "format=yuv420p," + ",".join(filters),
        "-map", "0:v", "-map", "1:a",
        *_encode_args(settings.end_card_seconds),
        str(tmp),
    )
    tmp.replace(out)
    return out


async def concat(parts: list[Path], out: Path) -> Path:
    out.parent.mkdir(parents=True, exist_ok=True)
    listing = out.with_suffix(".concat.txt")
    listing.write_text("".join(f"file '{p.resolve()}'\n" for p in parts), encoding="utf-8")
    tmp = out.with_suffix(".tmp.mp4")
    await run("ffmpeg", "-y", "-v", "error", "-f", "concat", "-safe", "0", "-i", str(listing), "-c", "copy", "-movflags", "+faststart", str(tmp))
    tmp.replace(out)
    return out


def _srt_time(t: float) -> str:
    ms = int(round(t * 1000))
    h, ms = divmod(ms, 3_600_000)
    m, ms = divmod(ms, 60_000)
    s, ms = divmod(ms, 1000)
    return f"{h:02d}:{m:02d}:{s:02d},{ms:03d}"


def write_srt(cues: list[tuple[float, float, str]], out: Path) -> Path:
    """Scene-level captions sidecar for muted autoplay (upload alongside the MP4)."""
    blocks = [f"{i}\n{_srt_time(a)} --> {_srt_time(b)}\n{text}\n" for i, (a, b, text) in enumerate(cues, start=1)]
    out.write_text("\n".join(blocks), encoding="utf-8")
    return out
